# Example of string manipulation in Python

nombre_persona = "Azul Virginia"
nombre_persona_2 = 'Ana Virginia'

print("Convertir mayuscula") 
print(nombre_persona.upper()) 
print(nombre_persona_2.upper())

print("\nConvertir minuscula")
print(nombre_persona.lower())
print(nombre_persona_2.lower())

print("\nRepetir cadena de caracteres")
print(nombre_persona * 3)
print(nombre_persona_2 * 3)

