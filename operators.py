variable_one = 12
variable_two = 111

# Addition 
plus_variable = variable_one + variable_two
print("Addition= " + str(plus_variable))

# Subtraction
minus_variable = variable_one - variable_two
print("Subtraction= " + str(minus_variable))

# Multiplication
multiplication_variable = variable_one * variable_two
print("Multiplication= " + str(multiplication_variable))

# Quotient 
quotient_variable = variable_one / variable_two
print("Quotient= " + str(quotient_variable))

# Quotient integer
quotient_variable_int = variable_one // variable_two
print("Quotient integer= " + str(quotient_variable_int))

# Module
module_variable = variable_one % variable_two
print("Module= " + str(module_variable))

# Potency
potency_variable = variable_one ** variable_two
print("Potency= " + str(potency_variable))




